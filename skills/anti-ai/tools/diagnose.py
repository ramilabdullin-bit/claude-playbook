def det_unicode(text_no_code):
    """Считаем по тексту без кода: внутри блоков кода эти символы законны."""
    found = []
    for ch, code, name in HARD_UNICODE:
        c = text_no_code.count(ch)
        if c:
            found.append({"code": code, "name": name, "count": c})
    esc = len(ESCAPE_RE.findall(text_no_code))
    if esc:
        found.append({"code": "escape", "name": "лишнее экранирование (\\. \\- \\! \\*)",
                      "count": esc})
    return found


