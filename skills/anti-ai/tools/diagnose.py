def analyse(raw, profile):
    prof = PROFILES[profile]
    code_free = strip_code(raw)
    text = strip_markup(strip_examples(raw))
    low = text.lower()
    sentences = split_sentences(text)
    paragraphs = split_paragraphs(raw)
    nwords = len(words_of(text))
    if nwords == 0:
        return None

    axes = {}
    axes["antithesis"] = det_antithesis(low, sentences)
    axes["semantic_hint"] = find_patterns(low, SEMANTIC_HINT, "смысловая антитеза")
    axes["staccato"] = det_staccato(sentences)
    axes["literary"] = find_patterns(low, LITERARY, "литоборот")
    axes["clerical"] = find_patterns(low, CLERICAL, "канцелярит")
    axes["impersonal"] = find_patterns(low, IMPERSONAL, "безличное/крючок")
    caught_by_colon = []
    axes["colon_hooks"] = det_colon_hooks(sentences, caught_by_colon)
    axes["superlative"] = det_superlative(sentences, low, caught_by_colon)
    axes["fake_qa"] = det_fake_qa(sentences)
    axes["parallel"] = det_parallel(sentences)
    axes["mirror"] = det_mirror(low, sentences)
    axes["repeat"] = det_repeat(sentences, paragraphs)
    axes["accusation"] = det_accusation(low)
    axes["scaffold"] = det_scaffold(raw, low, sentences)
    axes["template"] = (find_patterns(low, TEMPLATE_START, "шаблонный старт", re.MULTILINE)
                        + find_patterns(low, TEMPLATE_END, "шаблонный финал"))
    axes["pressure"] = find_patterns(low, PRESSURE, "давление/мотивашка")
    axes["reassurance"] = find_patterns(low, REASSURANCE, "заверение в честности")
    axes["calque"] = find_patterns(low, CALQUE, "калька")
    axes["rhetorical"] = find_patterns(low, RHETORICAL, "риторический крючок")
    axes["punch"] = det_punch(sentences)
    # Справочные оси: в p["axes"] их нет ни в одном профиле, поэтому gate()
    # их не смотрит, и в SUMMED они не входят. Печатаются всегда.
    axes["abstract"] = det_abstract(low)
    axes["slogan"] = det_slogan(sentences)
    axes["legal"] = (find_patterns(low, LEGAL_EDU, "юр. лексика")
                     + find_patterns(text, LEGAL_EDU_CASED, "юр. лексика"))
    axes["anglicism"] = find_patterns(low, ANGLICISM, "англицизм")
    axes["corporate"] = find_patterns(low, CORPORATE, "корп. вода")
    axes["pseudoproof"] = find_patterns(low, PSEUDOPROOF, "псевдопруф")
    axes["metaphor"] = find_patterns(low, BORROWED_METAPHOR, "чужая метафора")
    par_n, par_hits = det_parasites(low)

    counts = {k: len(v) for k, v in axes.items()}
    counts["parasite"] = par_n
    axes["parasite"] = par_hits

    def per1k(x):
        return round(x * 1000.0 / nwords, 2)

    info = set(INFO_NOTE.get(profile, {}))
    total = sum(counts[k] for k in SUMMED if k not in info)
    self_n = det_self(low)

    return {
        "words": nwords,
        "counts": counts,
        "per_1k": {k: per1k(v) for k, v in counts.items()},
        "marker_total": total,
        "total_per_1k": per1k(total),
        "self_count": self_n,
        "self_per_1k": per1k(self_n),
        "unicode": det_unicode(code_free),
        "rhythm": (rhythm(raw, sentences) if prof["rhythm_gate"]
                   else {"skipped": True, "sentences": len(sentences)}),
        "profile": profile,
        "_hits": axes,
    }


def gate(m, prof):
    p = PROFILES[prof]
    fails = []
    if p["unicode_gate"] and m["unicode"]:
        fails.append("типографика")
    if m["marker_total"] > 2 and m["total_per_1k"] > p["total_per_1k"]:
        fails.append("суммарная плотность")
    for key, (lo, cap) in p["axes"].items():
        if m["counts"].get(key, 0) > lo and m["per_1k"].get(key, 0.0) > cap:
            fails.append(AXIS_FAIL_NAME.get(key, key))
    floor = p["self_per_1k_min"]
    if (floor is not None and m["words"] >= p["self_min_words"]
            and m["self_per_1k"] < floor):
        fails.append("плотность «я» ниже порога")
    if p["rhythm_gate"]:
        r = m["rhythm"]
        if r["sentences"] >= 10 and r["cv"] < p["cv_fail"]:
            fails.append("ровный ритм")
        if r["paragraphs_counted"] >= 5 and r["short_final_pct"] > p["short_final_pct"]:
            fails.append("метроном финалов")
    return fails


def render(m, fails, limit):
    prof = m["profile"]
    p = PROFILES[prof]
    notes = INFO_NOTE.get(prof, {})
    out = []
    verdict = "ПРОВАЛ" if fails else "В ПОРЯДКЕ"
    out.append("Диагностика: %s   (%d слов, %d предложений, профиль %s: %s)"
               % (verdict, m["words"], m["rhythm"]["sentences"], prof, p["title"]))
    out.append("")
    for key, label in AXIS_ORDER:
        thr = p["axes"].get(key)
        if thr is not None:
            tail = "порог >%d и >%.1f /1k" % thr
        elif key in notes:
            tail = "справка: " + notes[key]
        elif key in SUMMED:
            tail = "в сумму маркеров"
        else:
            tail = "справка"
        out.append("  %-40s %4d   %6.2f /1k   %s"
                   % (label, m["counts"][key], m["per_1k"][key], tail))
    out.append("  %-40s %4d   %6.2f /1k   порог ≤%.1f"
               % ("─ сумма маркеров", m["marker_total"], m["total_per_1k"],
                  p["total_per_1k"]))
    floor = p["self_per_1k_min"]
    if floor is None:
        self_tail = "справка"
    elif m["words"] < p["self_min_words"]:
        self_tail = "порог с %d слов, тут короче" % p["self_min_words"]
    else:
        self_tail = "порог снизу ≥%.1f /1k" % floor
    out.append("  %-40s %4d   %6.2f /1k   %s"
               % ("плотность «я»", m["self_count"], m["self_per_1k"], self_tail))
    out.append("")
    if m["unicode"]:
        head = ("Типографика (жёсткий флаг):" if p["unicode_gate"]
                else "Типографика от распознавалки, чиним молча "
                     "(python3 tools/fix-typography.py FILE):")
        out.append("  " + head)
        for f in m["unicode"]:
            out.append("    %-10s %-40s ×%d" % (f["code"], f["name"], f["count"]))
    else:
        out.append("  Типографика: чисто.")
    out.append("")
    r = m["rhythm"]
    if r.get("skipped"):
        out.append("  Ритм: не считаем. В расшифровке нет расставленной "
                   "пунктуации, разброс длин и метроном финалов дадут мусор.")
    else:
        out.append("  Ритм:")
        out.append("    средняя длина предложения : %.1f знаков" % r["mean_sentence_chars"])
        zone = ("живой" if r["cv"] >= p["cv_good"]
                else "средний" if r["cv"] >= p["cv_fail"] else "машинная ровность")
        out.append("    разброс длин (CV)         : %.3f   %s (живой ≥%.2f, провал <%.2f)"
                   % (r["cv"], zone, p["cv_good"], p["cv_fail"]))
        out.append("    абзацы с финалом <75 зн.  : %d из %d = %.1f%%   (цель ≤%.0f%%)"
                   % (r["short_final_paragraphs"], r["paragraphs_counted"],
                      r["short_final_pct"], p["short_final_pct"]))
    out.append("")
    if fails:
        out.append("  Провалено: " + ", ".join(fails))
        out.append("")
        out.append("  Находки с цитатами:")
        for key, label in AXIS_ORDER:
            hits = m["_hits"].get(key) or []
            if not hits:
                continue
            out.append("   [%s]" % label)
            for h in hits[:limit]:
                out.append("     • " + h)
            if len(hits) > limit:
                out.append("     ... ещё %d" % (len(hits) - limit))
        if not r.get("skipped") and r["short_final_examples"]:
            out.append("   [короткие финалы абзацев]")
            for h in r["short_final_examples"][:limit]:
                out.append("     • " + h)
    else:
        out.append("  Механика чиста. Дальше - чтение вслух живым человеком.")
    # Абстракции и слоганы показываются всегда, даже при чистом вердикте.
    # Плотность для них - плохой инструмент: одна абстракция на сорок тысяч
    # слов ничего не значит, одна в заголовке из двенадцати слов убивает фразу.
    # Поэтому гейта по /1k у этих осей нет, есть список для глаза. При провале
    # их цитаты уже напечатаны общим списком находок выше.
    extra = (m["_hits"].get("slogan") or []) + (m["_hits"].get("abstract") or [])
    if extra and not fails:
        out.append("")
        out.append("  Ниже гейта, но посмотреть глазами:")
        for h in extra[:limit]:
            out.append("    - " + h)
        if len(extra) > limit:
            out.append("    ... ещё %d" % (len(extra) - limit))
    return "\n".join(out)


# ─────────────────── перезамер порогов по корпусу ───────────────────

CORPUS_EXT = (".md", ".txt")
CALIBRATE_MIN_WORDS = 200


def collect_files(root):
    if os.path.isfile(root):
        return [root]
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if not d.startswith(".")]
        for fn in sorted(filenames):
            if fn.startswith("."):
                continue
            if fn.lower().endswith(CORPUS_EXT):
                out.append(os.path.join(dirpath, fn))
    return sorted(out)


def percentile(values, q):
    if not values:
        return 0.0
    s = sorted(values)
    k = int(math.ceil(q / 100.0 * len(s))) - 1
    return s[max(0, min(len(s) - 1, k))]


def bump(x):
    """Потолок из замера: p90 плюс четверть запаса, шаг 0,5."""
    if x <= 0:
        return 0.0
    return math.ceil(x * 1.25 * 2) / 2.0


def calibrate(root, name, as_json, limit_rows=40):
    files = collect_files(root)
    rows, skipped = [], []
    for f in files:
        try:
            raw = open(f, encoding="utf-8", errors="replace").read()
        except OSError as e:
            skipped.append("%s: %s" % (f, e))
            continue
        m = analyse(raw, "text")
        if m is None:
            skipped.append("%s: нет слов" % f)
            continue
        if m["words"] < CALIBRATE_MIN_WORDS:
            skipped.append("%s: %d слов, плотность недостоверна" % (f, m["words"]))
            continue
        rows.append((os.path.relpath(f, root if os.path.isdir(root) else "."), m))
    if not rows:
        return None, "в корпусе нет файлов от %d слов" % CALIBRATE_MIN_WORDS

    stats = {}
    for key, _ in AXIS_ORDER:
        dens = [m["per_1k"][key] for _, m in rows]
        cnts = [m["counts"][key] for _, m in rows]
        stats[key] = {
            "median": percentile(dens, 50), "p75": percentile(dens, 75),
            "p90": percentile(dens, 90), "max": max(dens),
            "count_p90": percentile(cnts, 90), "count_max": max(cnts),
        }
    totals = [m["total_per_1k"] for _, m in rows]
    selfs = [m["self_per_1k"] for _, m in rows]
    cvs = [m["rhythm"]["cv"] for _, m in rows if not m["rhythm"].get("skipped")]
    finals = [m["rhythm"]["short_final_pct"] for _, m in rows
              if not m["rhythm"].get("skipped") and m["rhythm"]["paragraphs_counted"] >= 5]

    suggested = {
        "axes": {k: ((0, 0.0) if k in DICTIONARY_AXES
                     else (int(stats[k]["count_p90"]), bump(stats[k]["p90"])))
                 for k in PROFILES["text"]["axes"]},
        "total_per_1k": bump(percentile(totals, 90)),
        "self_per_1k_min": math.floor(percentile(selfs, 10) * 2) / 2.0,
        "cv_fail": round(max(0.20, percentile(cvs, 10) * 0.9), 2) if cvs else 0.40,
        "short_final_pct": round(min(90.0, bump(percentile(finals, 90))), 1) if finals else 45.0,
    }

    payload = {
        "corpus": root,
        "files": len(rows),
        "words": sum(m["words"] for _, m in rows),
        "skipped": skipped,
        "per_file": [{"file": f, "words": m["words"],
                      "total_per_1k": m["total_per_1k"],
                      "parasite_per_1k": m["per_1k"]["parasite"],
                      "self_per_1k": m["self_per_1k"],
                      "cv": m["rhythm"].get("cv")} for f, m in rows],
        "axes": stats,
        "suggested": suggested,
        "name": name,
    }
    if as_json:
        return payload, None

    out = []
    out.append("Перезамер порогов по корпусу: %s" % root)
    out.append("В корпус кладём только готовые тексты автора. Файл, который "
               "цитирует плохие примеры, задерёт пороги и обнулит проверку.")
    out.append("файлов в замере: %d, слов: %d" % (payload["files"], payload["words"]))
    if skipped:
        out.append("вне замера: %d (короткие или нечитаемые)" % len(skipped))
    out.append("")
    out.append("Сырые плотности по файлам (на 1000 слов):")
    out.append("  %-38s %6s %8s %9s %7s %6s" %
               ("файл", "слов", "маркеры", "паразиты", "«я»", "CV"))
    for f, m in rows[:limit_rows]:
        out.append("  %-38s %6d %8.2f %9.2f %7.2f %6s"
                   % (f[-38:], m["words"], m["total_per_1k"],
                      m["per_1k"]["parasite"], m["self_per_1k"],
                      ("%.3f" % m["rhythm"]["cv"]) if not m["rhythm"].get("skipped") else "-"))
    if len(rows) > limit_rows:
        out.append("  ... ещё %d файлов" % (len(rows) - limit_rows))
    out.append("")
    out.append("Плотности по осям (на 1000 слов):")
    out.append("  %-40s %8s %7s %7s %7s %9s" %
               ("ось", "медиана", "p75", "p90", "макс", "счёт p90"))
    for key, label in AXIS_ORDER:
        s = stats[key]
        out.append("  %-40s %8.2f %7.2f %7.2f %7.2f %9d"
                   % (label, s["median"], s["p75"], s["p90"], s["max"],
                      int(s["count_p90"])))
    out.append("  %-40s %8.2f %7.2f %7.2f %7.2f" %
               ("─ сумма маркеров", percentile(totals, 50), percentile(totals, 75),
                percentile(totals, 90), max(totals)))
    out.append("  %-40s %8.2f %7.2f %7.2f %7.2f" %
               ("плотность «я»", percentile(selfs, 50), percentile(selfs, 75),
                percentile(selfs, 90), max(selfs)))
    out.append("")
    out.append("Порог берём как p90 плюс четверть запаса. Словарные оси "
               "(юр. лексика, англицизмы, вода, псевдопруфы, метафоры)")
    out.append("замеру не подлежат: у них ноль по канону, и корпус автора "
               "этих слов не содержит. Готовый блок в PROFILES:")
    out.append("")
    out.append('    "%s": {' % name)
    out.append('        "title": "корпус автора",')
    out.append('        "axes": {')
    for key in PROFILES["text"]["axes"]:
        lo, cap = suggested["axes"][key]
        out.append('            "%s": (%d, %.1f),' % (key, lo, cap))
    out.append("        },")
    out.append('        "total_per_1k": %.1f,' % suggested["total_per_1k"])
    out.append('        "self_per_1k_min": %.1f,' % suggested["self_per_1k_min"])
    out.append('        "self_min_words": 400,')
    out.append('        "unicode_gate": True,')
    out.append('        "rhythm_gate": True,')
    out.append('        "cv_fail": %.2f,' % suggested["cv_fail"])
    out.append('        "cv_good": 0.55,')
    out.append('        "short_final_pct": %.1f,' % suggested["short_final_pct"])
    out.append("    },")
    out.append("")
    out.append("Дальше: вставить блок в PROFILES, дописать имя в PROFILE_ORDER "
               "по месту строгости и прогнать --selftest.")
    return "\n".join(out), None


