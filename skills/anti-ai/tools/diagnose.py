def check_monotonic():
    """Профиль правее по списку не должен быть строже профиля левее."""
    bad = []
    for i in range(len(PROFILE_ORDER) - 1):
        tight, loose = PROFILE_ORDER[i], PROFILE_ORDER[i + 1]
        a, b = PROFILES[tight], PROFILES[loose]
        for key, (lo_a, cap_a) in a["axes"].items():
            if key not in b["axes"]:
                continue
            lo_b, cap_b = b["axes"][key]
            if lo_b < lo_a or cap_b < cap_a:
                bad.append("%s строже %s по оси %s: (%d, %.2f) против (%d, %.2f)"
                           % (loose, tight, key, lo_b, cap_b, lo_a, cap_a))
        for key in b["axes"]:
            if key not in a["axes"]:
                bad.append("%s гейтит ось %s, которой нет в %s" % (loose, key, tight))
        if b["total_per_1k"] < a["total_per_1k"]:
            bad.append("%s строже %s по сумме маркеров" % (loose, tight))
        if b["short_final_pct"] < a["short_final_pct"]:
            bad.append("%s строже %s по метроному финалов" % (loose, tight))
        if b["cv_fail"] > a["cv_fail"]:
            bad.append("%s строже %s по разбросу длин" % (loose, tight))
        if b["unicode_gate"] and not a["unicode_gate"]:
            bad.append("%s гейтит типографику, а %s нет" % (loose, tight))
        if b["rhythm_gate"] and not a["rhythm_gate"]:
            bad.append("%s гейтит ритм, а %s нет" % (loose, tight))
        sa, sb = a["self_per_1k_min"], b["self_per_1k_min"]
        if sa is not None and sb is not None and sb > sa:
            bad.append("%s требует больше «я», чем %s" % (loose, tight))
        if sa is None and sb is not None:
            bad.append("%s гейтит плотность «я», а %s нет" % (loose, tight))
    return bad


