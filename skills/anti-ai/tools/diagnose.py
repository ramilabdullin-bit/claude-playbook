def strip_code(raw):
    """Снять код и оставить всё остальное как есть: для счёта типографики."""
    text = re.sub(r"^---\n.*?\n---\n", " ", raw, flags=re.DOTALL)
    # Забор длиннее трёх знаков законен: ````bash ... ```` обёртывает пример,
    # внутри которого сами тройные кавычки. Жадный шаблон на ровно три знака
    # такой блок не закрывал, и код из него уезжал в счёт как проза.
    text = re.sub(r"^[ \t]{0,3}(`{3,}|~{3,})[^\n]*\n.*?^[ \t]{0,3}\1[ \t]*$",
                  " ", text, flags=re.DOTALL | re.MULTILINE)
    text = re.sub(r"```.*?```", " ", text, flags=re.DOTALL)
    text = re.sub(r"~~~.*?~~~", " ", text, flags=re.DOTALL)
    text = re.sub(r"<pre[\s\S]*?</pre>", " ", text, flags=re.IGNORECASE)
    text = re.sub(r"<code[\s\S]*?</code>", " ", text, flags=re.IGNORECASE)
    text = re.sub(r"`[^`]*`", " ", text)
    return text


def strip_examples(raw):
    """Снять цитаты и строки таблиц: это данные, а не проза автора.

    Правка в чужую цитату не идёт ни на одном этапе, значит и счёт по ней
    не идёт: находка, которую ни один этап не имеет права закрыть, - шум.
    Под это же правило попадает строка таблицы: в разборе она стоит словарём
    запрещённого, и счёт по левой колонке ловит сам словарь.

    Типографика и метроном финалов считаются мимо этой функции: символ
    в цитате правится, а абзацы тела и так берутся из исходной разметки.
    """
    text = re.sub(r"^[ \t]{0,3}\|.*$", " ", raw, flags=re.MULTILINE)
    text = re.sub(r"«[^«»]{0,400}»", " ", text, flags=re.DOTALL)
    return text


def strip_markup(text):
    """Снять разметку и код, сохранив пунктуацию: её мы и проверяем."""
    text = strip_code(text)
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", " ", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"^\s*#{1,6}\s*", " ", text, flags=re.MULTILINE)
    # Жирная врезка в начале строки - подзаголовок пункта, а не предложение:
    # «**Стаккато.** Три одиночных слова...» иначе даёт панч-обрывок «Стаккато.»
    text = re.sub(r"^(\s{0,6}(?:[-*+•]\s+|\d{1,3}[.)]\s+)?)\*\*([^*\n]{1,40}?)\.\*\*[ \t]+",
                  r"\1\2 ", text, flags=re.MULTILINE)
    text = re.sub(r"^\s{0,6}(?:[-*+•]|\d{1,3}[.)])\s+", " ", text, flags=re.MULTILINE)
    text = re.sub(r"[*_>|~]", " ", text)
    return text


# мягкий перенос строки: конец строки без знака конца предложения, следующая
# строка начинается со строчной буквы или открывающего знака. В исходнике
# с жёсткой вёрсткой такой перенос резал предложения пополам, и обрубки уезжали
# в панч-обрывки, в стаккато и в разброс длин.
SOFT_WRAP = re.compile(
    r"(?<=[^.!?…:;\n\s])[ \t]*\n[ \t]*(?=[a-zа-яё0-9(«\"'-])")


def split_sentences(text):
    text = SOFT_WRAP.sub(" ", text)
    parts = re.split(r"(?<=[.!?…])\s+|\n+", text)
    return [p.strip() for p in parts if p.strip()]


def split_paragraphs(raw):
    body = re.sub(r"^---\n.*?\n---\n", "", raw, flags=re.DOTALL)
    body = re.sub(r"```.*?```", "", body, flags=re.DOTALL)
    out = []
    for p in body.split("\n\n"):
        p = p.strip()
        if not p:
            continue
        if p[0] in "#|<>`-*+" or re.match(r"^\d+[.)]\s", p):
            continue
        out.append(re.sub(r"\s+", " ", p))
    return out


def headings_of(raw):
    body = re.sub(r"```.*?```", "", raw, flags=re.DOTALL)
    return [h.strip() for h in re.findall(r"^\s{0,3}#{1,6}\s+(.+?)\s*$", body,
                                          flags=re.MULTILINE) if h.strip()]


def first_word(sent):
    m = re.match(r"[\W\d_]*([a-zа-яё]+)", sent.lower())
    return m.group(1) if m else ""


def words_of(text):
    return re.findall(r"[a-zа-яёA-ZА-ЯЁ]+", text)


def content_words(text, minlen=4):
    return [w for w in re.findall(r"[а-яёa-z]+", text.lower())
            if len(w) >= minlen and w not in ECHO_STOP and w not in CONNECTOR_STARTS
            and w not in PRONOUNS]


def find_patterns(low, patterns, label, flags=0):
    """Пересекающиеся совпадения внутри одной оси считаются один раз:
    два шаблона на одну фразу - это одна находка."""
    hits, spans = [], []
    for pat in patterns:
        for m in re.finditer(pat, low, flags | re.DOTALL):
            if any(m.start() < e and st < m.end() for st, e in spans):
                continue
            spans.append((m.start(), m.end()))
            frag = re.sub(r"\s+", " ", low[max(0, m.start() - 25):m.end() + 25]).strip()
            hits.append("%s: ...%s..." % (label, frag[:90]))
    return hits


