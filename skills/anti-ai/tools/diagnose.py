def rhythm(raw, sentences):
    lens = [len(s) for s in sentences]
    n = len(lens)
    cv = 0.0
    mean = 0.0
    if n >= 5:
        mean = sum(lens) / n
        var = sum((x - mean) ** 2 for x in lens) / n
        cv = math.sqrt(var) / mean if mean else 0.0
    paras = split_paragraphs(raw)
    short, counted, examples = 0, 0, []
    for p in paras:
        ss = [x for x in re.split(r"(?<=[.!?])\s+", p) if len(x) > 3]
        if not ss:
            continue
        # Абзац в одно предложение из знаменателя не выпадает: схлопнутый
        # знаменатель прячет ровно те абзацы, которые метроном и создаёт.
        # Абзац, закрытый двоеточием, - подводка к списку, таблице или коду,
        # финала у него нет и срастить его не с чем.
        if ss[-1].rstrip().endswith(":"):
            continue
        counted += 1
        if len(ss[-1]) < 75:
            short += 1
            if len(examples) < 8:
                examples.append(ss[-1][:80])
    pct = round(short * 100.0 / counted, 1) if counted else 0.0
    return {
        "skipped": False,
        "sentences": n,
        "mean_sentence_chars": round(mean, 1),
        "cv": round(cv, 3),
        "paragraphs_counted": counted,
        "short_final_paragraphs": short,
        "short_final_pct": pct,
        "short_final_examples": examples,
    }


